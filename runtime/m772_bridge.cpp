/* Build-time catalogue self-check: these entries must exist for the four
 * embedded SPU images and the NPUA WWS PM. This does not prove what bytes the
 * guest passes at runtime; cellSpursCopyAscensionPmDiagnostics records that
 * actual EA, size and fingerprint per workload. */
static uint32_t m772_count_registered_spu_images(void)
{
    static const uint64_t fingerprints[] = {
        UINT64_C(0x574361C36D1A4C05), UINT64_C(0xF4C2A58BDE92CE5E),
        UINT64_C(0x4DA69B4166D997AD), UINT64_C(0x00E729804474449A),
        UINT64_C(0xC8D774963A96DCF2)
    };
    uint32_t count = 0;
    for (unsigned i = 0; i < sizeof(fingerprints) / sizeof(fingerprints[0]); ++i) {
        int image_id = 0;
        if (spu_workload_find_img(fingerprints[i], &image_id) && image_id == (int)i + 1)
            ++count;
    }
    return count;
}

/* Reports should describe the current import attempt instead of leaving
 * counters from an earlier ELF run visible during the next preflight. */
extern "C" void ar_m772_runtime_begin(void)
{
    __atomic_store_n(&m772_initialized, 0u, __ATOMIC_RELEASE);
    __atomic_store_n(&m772_guest_vm_size, 0u, __ATOMIC_RELAXED);
    __atomic_store_n(&m772_registered_spu_images, 0u, __ATOMIC_RELAXED);
    __atomic_store_n(&m772_dispatch_count, UINT64_C(0), __ATOMIC_RELAXED);
    __atomic_store_n(&m772_entry_count, UINT64_C(0), __ATOMIC_RELAXED);
    __atomic_store_n(&m772_last_guest_pc, 0u, __ATOMIC_RELAXED);
    __atomic_store_n(&m772_last_guest_lr, UINT64_C(0), __ATOMIC_RELAXED);
    __atomic_store_n(&m772_last_guest_sp, UINT64_C(0), __ATOMIC_RELAXED);
    for (unsigned i = 0; i < 8; ++i)
        __atomic_store_n(&m772_last_guest_args[i], UINT64_C(0), __ATOMIC_RELAXED);
    __atomic_store_n(&m772_hle_call_count, UINT64_C(0), __ATOMIC_RELAXED);
    __atomic_store_n(&m772_last_hle_nid, 0u, __ATOMIC_RELAXED);
    __atomic_store_n(&m772_last_hle_lr, 0u, __ATOMIC_RELAXED);
    __atomic_store_n(&m772_syscall_count, UINT64_C(0), __ATOMIC_RELAXED);
    __atomic_store_n(&m772_last_syscall_number, 0u, __ATOMIC_RELAXED);
    __atomic_store_n(&m772_last_syscall_lr, 0u, __ATOMIC_RELAXED);
    __atomic_store_n(&m772_hotloop_count, UINT64_C(0), __ATOMIC_RELAXED);
    __atomic_store_n(&m772_last_hotloop_pc, 0u, __ATOMIC_RELAXED);
    for (unsigned i = 0; i < 5; ++i)
        __atomic_store_n(&m772_last_hotloop_regs[i], UINT64_C(0), __ATOMIC_RELAXED);
    __atomic_store_n(&m772_unresolved_hle_count, UINT64_C(0), __ATOMIC_RELAXED);
    __atomic_store_n(&m772_last_unresolved_hle_nid, 0u, __ATOMIC_RELAXED);
    __atomic_store_n(&m772_last_unresolved_hle_lr, 0u, __ATOMIC_RELAXED);
    __atomic_store_n(&m772_aot_trace_write_index, UINT64_C(0), __ATOMIC_RELAXED);
    __atomic_store_n(&m772_hle_trace_write_index, UINT64_C(0), __ATOMIC_RELAXED);
    __atomic_store_n(&m772_unresolved_trace_write_index, UINT64_C(0), __ATOMIC_RELAXED);
    __atomic_store_n(&m772_entry_state, 0u, __ATOMIC_RELAXED);
    __atomic_store_n(&m772_vfs_root_set, 0u, __ATOMIC_RELEASE);
    ppu_fs_ios_reset_stats();
}

static void m772_register_all(void)
{
    for (uint64_t i = 1; i < function_table_count; ++i)
        if (function_table[i - 1].addr >= function_table[i].addr)
            m772_sorted_table = 0;
    ppu_recomp_register();
    ppu_hle_init();
    ppu_sysprx_register();
    ppu_fs_register();
    lv2_init_syscalls();
    ppu_install_thread_trampoline();
    gowa_spu_register_all();
    ppu_fs_ios_reset_stats();
}

extern "C" int ar_m772_runtime_init(uint8_t* guest_memory,size_t guest_size,
                                      const char* game_root)
{
    if (!guest_memory || !guest_size || guest_size > UINT32_MAX ||
        !game_root || !*game_root) return -1;
    /* PS3 guest addresses are offsets from vm_base. HLE pointer-to-EA
     * conversion subtracts this base, so LiveContainer can supply any free
     * 4-GiB virtual extent; the separate 16 MiB graphics probe arena must
     * never be used for guest PPU execution. */
    if (guest_size != (size_t)UINT32_C(0xE0000000)) return -2;
    vm_base = guest_memory;
    ppu_vm_size = (uint32_t)guest_size;
    m772_vfs_root.assign(game_root);
    ppu_vfs_root = m772_vfs_root.c_str();
    ppu_fs_ios_reset_stats();
    __atomic_store_n(&m772_vfs_root_set, 1u, __ATOMIC_RELEASE);
    __atomic_store_n(&m772_dispatch_count, UINT64_C(0), __ATOMIC_RELAXED);
    __atomic_store_n(&m772_entry_count, UINT64_C(0), __ATOMIC_RELAXED);
    __atomic_store_n(&m772_last_guest_pc, 0u, __ATOMIC_RELAXED);
    __atomic_store_n(&m772_entry_state, 0u, __ATOMIC_RELAXED);
    __atomic_store_n(&m772_guest_vm_size,(uint32_t)guest_size,__ATOMIC_RELAXED);
    pthread_once(&m772_once, m772_register_all);
    __atomic_store_n(&m772_registered_spu_images,
                     m772_count_registered_spu_images(), __ATOMIC_RELAXED);
    __atomic_store_n(&m772_initialized, 1u, __ATOMIC_RELEASE);
    return 0;
}

/* Match the PS3Recomp process-entry state before entering the ELF OPD.  The
 * iOS host uses its own ELF/VFS owner, so it cannot call upstream ppu_run(),
 * but the guest CRT still requires the same LV2 thread identity, TLS image,
 * reservation registration and command-line ABI. */
extern "C" int ar_m772_prepare_main(ppu_context* ctx,uint32_t tls_vaddr,
                                     uint32_t tls_filesz,uint32_t tls_memsz,
                                     uint32_t tls_image,uint32_t stack_top,
                                     uint32_t argv_base)
{
    if (!ctx || !vm_base || !ppu_vm_size || !stack_top || !argv_base ||
        tls_filesz > tls_memsz || tls_memsz > 1024u*1024u ||
        tls_vaddr > ppu_vm_size || tls_filesz > ppu_vm_size - tls_vaddr ||
        tls_image > ppu_vm_size || tls_memsz > ppu_vm_size - tls_image ||
        argv_base > ppu_vm_size - 24u ||
        stack_top > ppu_vm_size || argv_base >= stack_top ||
        tls_image < stack_top)
        return -1;

    ctx->thread_id = ppu_thread_register_main();
    if (!ctx->thread_id) return -2;
    g_ppu_main_ctx = ctx;
    g_active_ctx = ctx;
    ppu_resv_register(ctx);

    ctx->gpr[7] = ctx->thread_id;
    ctx->gpr[8] = tls_vaddr;
    ctx->gpr[9] = tls_filesz;
    ctx->gpr[10] = tls_memsz;
    ctx->gpr[12] = 0x100000u;
    if (tls_memsz) {
        memcpy(vm_base + tls_image, vm_base + tls_vaddr, tls_filesz);
        if (tls_memsz > tls_filesz)
            memset(vm_base + tls_image + tls_filesz, 0, tls_memsz - tls_filesz);
        ctx->gpr[13] = (uint64_t)tls_image + 0x7000u;
    }

    /* argc=1; argv[0] is the real disc boot path. PPU pointers occupy the
     * low 32 bits of big-endian 64-bit slots, as in upstream ppu_run(). */
    ctx->gpr[3] = 1;
    ctx->gpr[4] = argv_base;
    ctx->gpr[5] = argv_base + 16u;
    ctx->gpr[6] = 0;
    return 0;
}

extern "C" void ar_m772_unbind_guest_memory(void* guest_memory)
{
    if (!guest_memory || vm_base != guest_memory) return;
    vm_base = nullptr;
    ppu_vm_size = 0;
    __atomic_store_n(&m772_guest_vm_size, 0u, __ATOMIC_RELEASE);
}

extern "C" int ar_m772_dispatch_native(ppu_context* ctx,uint32_t pc)
{
    /* Kept as a fail-closed compatibility hook for the fragment runner.
     * A complete PS3Recomp function cannot return a "next PC" via LR. */
    (void)ctx; (void)pc;
    return 0;
}

/* Inserted at the start of every complete PS3Recomp PPU function during
 * staging. This counts actual AOT calls from direct edges and trampolines. */
static void m772_snapshot_context(ppu_context* ctx)
{
    if (!ctx) return;
    __atomic_store_n(&m772_last_guest_lr, ctx->lr, __ATOMIC_RELAXED);
    __atomic_store_n(&m772_last_guest_sp, ctx->gpr[1], __ATOMIC_RELAXED);
    for (unsigned i = 0; i < 8; ++i)
        __atomic_store_n(&m772_last_guest_args[i], ctx->gpr[i + 3], __ATOMIC_RELAXED);
}

extern "C" void ar_m772_note_function(uint32_t pc, ppu_context* ctx)
{
    const uint64_t calls = __atomic_add_fetch(&m772_dispatch_count, UINT64_C(1), __ATOMIC_RELAXED);
    __atomic_store_n(&m772_last_guest_pc, pc, __ATOMIC_RELAXED);
    /* Sample 1 in 4096 calls to keep the hot-path cost bounded. The report
     * identifies these as function-entry samples, never as the live PPC PC. */
    if ((calls & UINT64_C(0xFFF)) == 0) {
        const uint64_t index = __atomic_fetch_add(&m772_aot_trace_write_index,
                                                  UINT64_C(1), __ATOMIC_RELAXED);
        const uint64_t caller = ctx ? (uint32_t)ctx->lr : 0;
        __atomic_store_n(&m772_aot_trace[index % M772_TRACE_CAPACITY],
                         ((uint64_t)pc << 32) | caller, __ATOMIC_RELAXED);
    }
    m772_snapshot_context(ctx);
}

extern "C" void ar_m772_note_hle(uint32_t nid, uint32_t guest_lr,
                                   ppu_context* ctx)
{
    __atomic_add_fetch(&m772_hle_call_count, UINT64_C(1), __ATOMIC_RELAXED);
    __atomic_store_n(&m772_last_hle_nid, nid, __ATOMIC_RELAXED);
    __atomic_store_n(&m772_last_hle_lr, guest_lr, __ATOMIC_RELAXED);
    const uint64_t index = __atomic_fetch_add(&m772_hle_trace_write_index,
                                              UINT64_C(1), __ATOMIC_RELAXED);
    __atomic_store_n(&m772_hle_trace[index % M772_TRACE_CAPACITY],
                     ((uint64_t)nid << 32) | guest_lr, __ATOMIC_RELAXED);
    m772_snapshot_context(ctx);
}

extern "C" void ar_m772_note_syscall(uint32_t number, uint32_t guest_lr,
                                        ppu_context* ctx)
{
    __atomic_add_fetch(&m772_syscall_count, UINT64_C(1), __ATOMIC_RELAXED);
    __atomic_store_n(&m772_last_syscall_number, number, __ATOMIC_RELAXED);
    __atomic_store_n(&m772_last_syscall_lr, guest_lr, __ATOMIC_RELAXED);
    m772_snapshot_context(ctx);
}

extern "C" void ar_m772_note_unresolved_hle(uint32_t nid, uint32_t guest_lr,
                                               ppu_context* ctx)
{
    __atomic_add_fetch(&m772_unresolved_hle_count, UINT64_C(1), __ATOMIC_RELAXED);
    __atomic_store_n(&m772_last_unresolved_hle_nid, nid, __ATOMIC_RELAXED);
    __atomic_store_n(&m772_last_unresolved_hle_lr, guest_lr, __ATOMIC_RELAXED);
    const uint64_t index = __atomic_fetch_add(&m772_unresolved_trace_write_index,
                                              UINT64_C(1), __ATOMIC_RELAXED);
    __atomic_store_n(&m772_unresolved_trace[index % M772_TRACE_CAPACITY],
                     ((uint64_t)nid << 32) | guest_lr, __ATOMIC_RELAXED);
    m772_snapshot_context(ctx);
}

static uint32_t m772_copy_trace(const uint64_t* trace, uint64_t total,
                                uint64_t* out, uint32_t capacity)
{
    if (!out || !capacity) return 0;
    uint32_t count = total < capacity ? (uint32_t)total : capacity;
    const uint64_t first = total - count;
    for (uint32_t i = 0; i < count; ++i)
        out[i] = __atomic_load_n(&trace[(first + i) % M772_TRACE_CAPACITY],
                                 __ATOMIC_RELAXED);
    return count;
}

extern "C" uint32_t ar_m772_copy_aot_trace(uint64_t* out, uint32_t capacity)
{
    const uint64_t total = __atomic_load_n(&m772_aot_trace_write_index, __ATOMIC_RELAXED);
    return m772_copy_trace(m772_aot_trace, total, out, capacity);
}

extern "C" uint32_t ar_m772_copy_hle_trace(uint64_t* out, uint32_t capacity)
{
    const uint64_t total = __atomic_load_n(&m772_hle_trace_write_index, __ATOMIC_RELAXED);
    return m772_copy_trace(m772_hle_trace, total, out, capacity);
}

extern "C" uint32_t ar_m772_copy_unresolved_hle_trace(uint64_t* out, uint32_t capacity)
{
    const uint64_t total = __atomic_load_n(&m772_unresolved_trace_write_index,
                                           __ATOMIC_RELAXED);
    return m772_copy_trace(m772_unresolved_trace, total, out, capacity);
}

extern "C" void ar_m772_note_hotloop(uint32_t guest_pc, ppu_context* ctx)
{
    if (!ctx) return;
    __atomic_add_fetch(&m772_hotloop_count, UINT64_C(1), __ATOMIC_RELAXED);
    __atomic_store_n(&m772_last_hotloop_pc, guest_pc, __ATOMIC_RELAXED);
    const unsigned indices[5] = {3, 4, 5, 8, 9};
    for (unsigned i = 0; i < 5; ++i)
        __atomic_store_n(&m772_last_hotloop_regs[i], ctx->gpr[indices[i]], __ATOMIC_RELAXED);
}

extern "C" int ar_m772_run_entry(ppu_context* ctx,uint32_t pc)
{
    if (!ctx || !pc || !m772_has_ppu(pc) ||
        !__atomic_load_n(&m772_initialized, __ATOMIC_ACQUIRE)) {
        __atomic_store_n(&m772_entry_state, 3u, __ATOMIC_RELEASE);
        return -1;
    }
    size_t index = (size_t)function_table_count;
    if (m772_sorted_table) {
        size_t lo = 0, hi = (size_t)function_table_count;
        while (lo < hi) {
            const size_t mid = lo + (hi - lo) / 2;
            if (function_table[mid].addr < pc) lo = mid + 1;
            else hi = mid;
        }
        if (lo < (size_t)function_table_count && function_table[lo].addr == pc)
            index = lo;
    } else {
        for (size_t i = 0; i < (size_t)function_table_count; ++i)
            if (function_table[i].addr == pc) { index = i; break; }
    }
    if (index >= (size_t)function_table_count || !function_table[index].func) {
        __atomic_store_n(&m772_entry_state, 3u, __ATOMIC_RELEASE);
        return -1;
    }

    __atomic_add_fetch(&m772_entry_count, UINT64_C(1), __ATOMIC_RELAXED);
    __atomic_store_n(&m772_last_guest_pc, pc, __ATOMIC_RELAXED);
    __atomic_store_n(&m772_entry_state, 1u, __ATOMIC_RELEASE);
    ctx->cia = pc;
    function_table[index].func(ctx);
    while (g_trampoline_fn) {
        void (*trampoline)(void*) = g_trampoline_fn;
        g_trampoline_fn = nullptr;
        trampoline(ctx);
    }
    if (g_active_ctx == ctx) g_active_ctx = nullptr;
    if (g_ppu_main_ctx == ctx)
        __atomic_store_n(&g_ppu_main_ctx, (ppu_context*)nullptr, __ATOMIC_RELEASE);
    __atomic_store_n(&m772_entry_state, 2u, __ATOMIC_RELEASE);
    return 0;
}

extern "C" uint32_t ar_m772_entry_state(void)
{
    return __atomic_load_n(&m772_entry_state, __ATOMIC_ACQUIRE);
}

static uint32_t m772_has_ppu(uint32_t pc)
{
    if (!m772_sorted_table) {
        for (uint64_t i = 0; i < function_table_count; ++i)
            if (function_table[i].addr == pc && function_table[i].func) return 1;
        return 0;
    }
    uint64_t lo = 0, hi = function_table_count;
    while (lo < hi) {
        const uint64_t mid = lo + (hi - lo) / 2;
        if (function_table[mid].addr < pc) lo = mid + 1;
        else hi = mid;
    }
    return lo < function_table_count && function_table[lo].addr == pc &&
           function_table[lo].func != nullptr;
}

extern "C" void ar_m772_runtime_attest(uint64_t out[40])
{
    if (!out) return;
    const uint32_t ready = __atomic_load_n(&m772_initialized, __ATOMIC_ACQUIRE);
    /* The UI may poll while runtime_init is registering thousands of entries.
     * Do not inspect the mutable registry until the release/acquire handshake. */
    out[0] = ready ? function_table_count : 0;
    out[1] = ready ? m772_has_ppu(0x0052A740u) : 0;
    out[2] = ready ? m772_has_ppu(0x0052E3F4u) : 0;
    out[3] = ready ? __atomic_load_n(&m772_registered_spu_images, __ATOMIC_RELAXED) : 0;
    out[4] = ready;
    out[5] = __atomic_load_n(&m772_dispatch_count, __ATOMIC_RELAXED);
    out[6] = __atomic_load_n(&m772_last_guest_pc, __ATOMIC_RELAXED);
    out[7] = __atomic_load_n(&m772_guest_vm_size, __ATOMIC_RELAXED);
    out[8] = __atomic_load_n(&m772_vfs_root_set, __ATOMIC_ACQUIRE);
    ppu_fs_ios_stats(out + 9);
    out[13] = __atomic_load_n(&m772_entry_count, __ATOMIC_RELAXED);
    out[14] = __atomic_load_n(&m772_last_guest_lr, __ATOMIC_RELAXED);
    out[15] = __atomic_load_n(&m772_last_guest_sp, __ATOMIC_RELAXED);
    for (unsigned i = 0; i < 8; ++i)
        out[16 + i] = __atomic_load_n(&m772_last_guest_args[i], __ATOMIC_RELAXED);
    out[24] = __atomic_load_n(&m772_last_hle_nid, __ATOMIC_RELAXED);
    out[25] = __atomic_load_n(&m772_last_hle_lr, __ATOMIC_RELAXED);
    out[26] = __atomic_load_n(&m772_hle_call_count, __ATOMIC_RELAXED);
    out[27] = __atomic_load_n(&m772_last_syscall_number, __ATOMIC_RELAXED);
    out[28] = __atomic_load_n(&m772_last_syscall_lr, __ATOMIC_RELAXED);
    out[29] = __atomic_load_n(&m772_syscall_count, __ATOMIC_RELAXED);
    out[30] = __atomic_load_n(&m772_hotloop_count, __ATOMIC_RELAXED);
    out[31] = __atomic_load_n(&m772_last_hotloop_pc, __ATOMIC_RELAXED);
    for (unsigned i = 0; i < 5; ++i)
        out[32 + i] = __atomic_load_n(&m772_last_hotloop_regs[i], __ATOMIC_RELAXED);
    out[37] = __atomic_load_n(&m772_unresolved_hle_count, __ATOMIC_RELAXED);
    out[38] = __atomic_load_n(&m772_last_unresolved_hle_nid, __ATOMIC_RELAXED);
    out[39] = __atomic_load_n(&m772_last_unresolved_hle_lr, __ATOMIC_RELAXED);
}
