#!/usr/bin/env python3
"""macOS finalizer: compile BOTW framework and Route C Shared Shell without game data."""
from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path


def run(command, cwd=None, env=None) -> None:
    print("+", " ".join(map(str, command)), flush=True)
    subprocess.run(list(map(str, command)), cwd=cwd, env=env, check=True)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--nx2apple-root", type=Path, required=True)
    parser.add_argument("--prepared-json", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    if sys.platform != "darwin":
        raise SystemExit("The Shared Shell finalizer must run on macOS.")

    nx = args.nx2apple_root.resolve()
    prepared = json.loads(args.prepared_json.read_text(encoding="utf-8"))
    nsp_dir = Path(prepared["nsp_dir"]).resolve()
    keys = Path(prepared["keys"]).resolve()
    work = Path(prepared["work_dir"]).resolve()
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=True)

    if prepared.get("title_id") != "01007EF00011E000" or prepared.get("package_version") != "v1114112":
        raise SystemExit("Refusing to build anything except BOTW 1.9.0 / v1114112.")
    if prepared.get("nx2apple_tag") != "v1.3.1-rc2":
        raise SystemExit("Unexpected NX2Apple release in prepared manifest.")
    pin = (nx / ".upstream-ref").read_text(encoding="utf-8").strip()
    if pin != prepared.get("engine_pin") or pin != "81906931262fb25d774cce8bca2db8926439e5a2":
        raise SystemExit("NX2Apple/NXNative pin mismatch; refusing a mixed build.")
    linux_prep = json.loads((work / "link2ios-linux-prep.json").read_text(encoding="utf-8"))
    if linux_prep.get("engine_pin") != pin:
        raise SystemExit("Colab's workspace was prepared with another engine commit.")
    if not nsp_dir.is_dir() or not keys.is_file() or not list(nsp_dir.glob("*.nsp")):
        raise SystemExit("Original NSP files or prod.keys are missing from the verified Drive download.")

    engine = nx / "engine"
    builder = engine / "scripts" / "build_ipa_from_nsp.py"
    framework_root = output / "frameworks"
    shutil.rmtree(framework_root, ignore_errors=True)
    framework_root.mkdir(parents=True)

    # Keep ordinary Metal shader libraries for the Metal 4 prebuild route.
    # Do not embed .mtl4a PSO archives generated by the newer SDK for the iOS 26 target.
    builder_env = os.environ.copy()
    builder_env["IOS_PULL"] = "1"
    command = [
        sys.executable, str(builder), str(nsp_dir), "-k", str(keys),
        "--title-id", prepared["title_id"], "--package", prepared["package_version"],
        "--work-dir", str(work), "--shell-framework", str(framework_root),
        "--keep-extracted", "--no-heap-check", "--progress", "lines", "--gpu", "none",
    ]
    run(command, cwd=nx, env=builder_env)

    title_id = prepared["title_id"]
    framework_name = f"DmGame{title_id}.framework"
    framework = framework_root / framework_name
    manifest_path = framework / "game.manifest.json"
    if not manifest_path.is_file():
        raise SystemExit(f"NXNative did not produce the Route C framework: {framework}")
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    if str(manifest.get("title_id", "")).upper() != title_id or manifest.get("framework") != framework_name:
        raise SystemExit("Route C framework manifest does not identify BOTW.")
    executable_name = manifest.get("framework_executable", "")
    if not executable_name or not (framework / executable_name).is_file():
        raise SystemExit("BOTW framework executable is missing.")
    if not (framework / "dm" / "shader_map.tsv").is_file():
        raise SystemExit("BOTW framework shader map is missing.")
    pso = framework / "pso"
    bad_pso = sorted(pso.rglob("*.mtl4a")) if pso.is_dir() else []
    if bad_pso:
        raise SystemExit("iOS 26 output unexpectedly contains .mtl4a PSO archives: " +
                         ", ".join(str(p.relative_to(framework)) for p in bad_pso))
    if not Path(prepared["romfs_path"]).is_file():
        raise SystemExit("External RomFS image disappeared before framework build completed.")

    shell_dir = output / "shell-project"
    shutil.rmtree(shell_dir, ignore_errors=True)
    shell_dir.mkdir(parents=True)
    shell_script = engine / "dm" / "ios" / "tools" / "build_shell.sh"
    shell_env = os.environ.copy()
    shell_env.update({
        "SHELL_DIR": str(shell_dir),
        "DM_SHELL_FRAMEWORKS": str(framework),
        "DM_SHELL_PACKAGE": str(nx / "frontend-ios"),
        "DM_SHELL_NAME": "Link2iOS",
        "DM_BUNDLE_ID": "org.nxnative.link2ios",
        "DM_APP_VERSION": "1.0.0",
        "DM_TEAM_ID": "0000000000",
        "FONT_PY": sys.executable,
        "STD_FONT": "/System/Library/Fonts/Supplemental/Arial Unicode.ttf",
    })
    run(["bash", str(shell_script), "--build"], cwd=engine, env=shell_env)

    app = shell_dir / "dd" / "Build" / "Products" / "Release-iphoneos" / "DmShell.app"
    if not (app / "DmShell").is_file():
        raise SystemExit(f"Route C Shared Shell app was not built: {app}")
    entitlements = shell_dir / "Gen" / "DmShell.entitlements"
    if not entitlements.is_file():
        raise SystemExit("build_shell.sh did not generate the app entitlements file.")

    # Framework code is signed first; Increased Memory Limit belongs to the app executable.
    for item in sorted((app / "Frameworks").glob("*.framework")):
        run(["xattr", "-cr", str(item)])
        run(["codesign", "--force", "--sign", "-", "--timestamp=none", str(item)])
        run(["codesign", "--verify", "--strict", str(item)])
    run(["xattr", "-cr", str(app)])
    run(["codesign", "--force", "--sign", "-", "--entitlements", str(entitlements),
         "--timestamp=none", str(app)])
    run(["codesign", "--verify", "--deep", "--strict", str(app)])
    entitlement_check = subprocess.run(
        ["codesign", "-d", "--entitlements", ":-", str(app / "DmShell")],
        capture_output=True, text=True, check=False,
    )
    if "com.apple.developer.kernel.increased-memory-limit" not in (
        entitlement_check.stdout + entitlement_check.stderr
    ):
        raise SystemExit("Ad-hoc signature is missing Increased Memory Limit.")

    ipa = output / "Link2iOS-BOTW.ipa"
    packer = engine / "dm" / "ios" / "tools" / "pack_ipa.py"
    run([sys.executable, str(packer), str(ipa), "--no-reuse",
         f"Payload/DmShell.app={app}"], cwd=engine)
    with zipfile.ZipFile(ipa) as archive:
        entries = archive.namelist()
        required = [
            "Payload/DmShell.app/DmShell",
            f"Payload/DmShell.app/Frameworks/{framework_name}/{executable_name}",
            f"Payload/DmShell.app/Frameworks/{framework_name}/game.manifest.json",
        ]
        missing = [name for name in required if name not in entries]
        if missing:
            raise SystemExit("Final IPA is missing required Route C components: " + ", ".join(missing))
        bundled_game_data = [
            name for name in entries
            if name.lower().endswith("/romfs.img")
            or "/aoc/" in name.lower()
            or name.lower().endswith(".nsp")
        ]
        if bundled_game_data:
            raise SystemExit("IPA unexpectedly contains game data: " + ", ".join(bundled_game_data[:20]))
        pso_entries = [name for name in entries if name.lower().endswith(".mtl4a")]
        if pso_entries:
            raise SystemExit("IPA unexpectedly contains .mtl4a: " + ", ".join(pso_entries[:20]))

    report = {
        "project": "Link2iOS",
        "game": "The Legend of Zelda: Breath of the Wild",
        "title_id": title_id,
        "display_version": manifest.get("display_version"),
        "package_version": prepared["package_version"],
        "nx2apple_tag": prepared["nx2apple_tag"],
        "engine_pin": pin,
        "framework": framework_name,
        "ipa": ipa.name,
        "ipa_size_bytes": ipa.stat().st_size,
        "ipa_contains_romfs": False,
        "ipa_contains_aoc": False,
        "external_game_data": {
            "drive_folder_url": prepared["game_data"]["folder_url"],
            "romfs_size_bytes": prepared["game_data"]["romfs"]["size"],
            "aoc_images": len(prepared["game_data"]["aoc"]),
            "layout": f"games/{title_id}/romfs.img + games/{title_id}/aoc/",
        },
        "pipeline_archive": {
            "included": False,
            "gpu": "none",
            "reason": "No .mtl4a archive is embedded for the iOS 26 target; the device builds Metal 4 pipeline bases from retained shader libraries on first use.",
        },
        "signature": "ad-hoc; sideloading re-sign is required",
        "entitlement": "com.apple.developer.kernel.increased-memory-limit",
    }
    (output / "build-report.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(report, indent=2))
    print(f"[Link2iOS] IPA complete: {ipa} ({ipa.stat().st_size:,} bytes)")
    print("[Link2iOS] Verified: RomFS, AOC, NSPs and .mtl4a are absent from the IPA.")


if __name__ == "__main__":
    main()
